
-- =====================================================
-- 1. KPI Overview
-- Main business metrics for the dashboard
-- =====================================================

CREATE OR REPLACE VIEW kpi_overview AS
WITH order_totals AS (
    SELECT
        o.order_id,
        o.customer_id,
        SUM(oi.item_total) AS order_total
    FROM orders o
    JOIN order_items oi
        ON o.order_id = oi.order_id
    WHERE o.order_status = 'delivered'
    GROUP BY o.order_id, o.customer_id
)
SELECT
    COUNT(*) AS total_delivered_orders,
    COUNT(DISTINCT c.customer_unique_id) AS total_unique_customers,
    ROUND(SUM(ot.order_total), 2) AS total_revenue,
    ROUND(AVG(ot.order_total), 2) AS average_order_value
FROM order_totals ot
JOIN customers c
    ON ot.customer_id = c.customer_id;


-- =====================================================
-- 2. Monthly Revenue
-- Revenue and order volume over time
-- =====================================================

CREATE OR REPLACE VIEW monthly_revenue AS
SELECT
    DATE_TRUNC('month', o.order_purchase_timestamp)::DATE AS month,
    COUNT(DISTINCT o.order_id) AS total_orders,
    COUNT(*) AS items_sold,
    ROUND(SUM(oi.item_total), 2) AS revenue
FROM orders o
JOIN order_items oi
    ON o.order_id = oi.order_id
WHERE o.order_status = 'delivered'
GROUP BY DATE_TRUNC('month', o.order_purchase_timestamp);


-- =====================================================
-- 3. Category Revenue
-- Revenue generated by each product category
-- =====================================================

CREATE OR REPLACE VIEW category_revenue AS
SELECT
    COALESCE(
        ct.product_category_name_english,
        p.product_category_name,
        'Unknown'
    ) AS category,
    COUNT(*) AS items_sold,
    COUNT(DISTINCT oi.order_id) AS total_orders,
    ROUND(SUM(oi.item_total), 2) AS revenue
FROM order_items oi
JOIN orders o
    ON oi.order_id = o.order_id
JOIN products p
    ON oi.product_id = p.product_id
LEFT JOIN category_translation ct
    ON p.product_category_name = ct.product_category_name
WHERE o.order_status = 'delivered'
GROUP BY category;


-- =====================================================
-- 4. Customer Metrics
-- Spending and order frequency per unique customer
-- =====================================================

CREATE OR REPLACE VIEW customer_metrics AS
SELECT
    c.customer_unique_id,
    COUNT(DISTINCT o.order_id) AS total_orders,
    ROUND(SUM(oi.item_total), 2) AS total_spent,
    ROUND(AVG(oi.item_total), 2) AS average_item_value
FROM customers c
JOIN orders o
    ON c.customer_id = o.customer_id
JOIN order_items oi
    ON o.order_id = oi.order_id
WHERE o.order_status = 'delivered'
GROUP BY c.customer_unique_id;


-- =====================================================
-- 5. Delivery Performance
-- Delivery time and late-delivery statistics by month
-- =====================================================

CREATE OR REPLACE VIEW delivery_performance AS
SELECT
    DATE_TRUNC('month', order_purchase_timestamp)::DATE AS month,
    COUNT(*) AS delivered_orders,
    ROUND(AVG(delivery_time_days), 2) AS avg_delivery_days,
    COUNT(*) FILTER (
        WHERE delivery_delay_days > 0
    ) AS late_orders,
    ROUND(
        100.0 * COUNT(*) FILTER (
            WHERE delivery_delay_days > 0
        ) / NULLIF(COUNT(*), 0),
        2
    ) AS late_delivery_percentage
FROM orders
WHERE order_status = 'delivered'
GROUP BY DATE_TRUNC('month', order_purchase_timestamp);


-- =====================================================
-- 6. Payment Analysis
-- Payment methods and amounts
-- =====================================================

CREATE OR REPLACE VIEW payment_analysis AS
SELECT
    payment_type,
    COUNT(*) AS payment_records,
    COUNT(DISTINCT order_id) AS total_orders,
    ROUND(SUM(payment_value), 2) AS total_payment,
    ROUND(AVG(payment_value), 2) AS average_payment
FROM payments
GROUP BY payment_type;
